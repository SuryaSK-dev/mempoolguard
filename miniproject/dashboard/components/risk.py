"""Risk Monitoring component displaying actual M6 inference outputs and scores."""

from __future__ import annotations

import streamlit as st

from dashboard.components.transactions import _format_hex
from dashboard.data_loader import DataLoader


def _get_risk_badge(score: float) -> str:
    """Return color-coded markdown badge based on canonical thresholds."""
    if score < 30.0:
        return f"🟢 Low ({score:.1f})"
    elif score <= 70.0:
        return f"🟡 Medium ({score:.1f})"
    return f"🔴 High ({score:.1f})"


def render_risk(data_loader: DataLoader) -> None:
    """Render the M6 Risk Monitoring section."""
    st.header("⚡ M6 Risk Score Monitoring")
    st.caption("Pre-confirmation risk scoring generated by Rule-Based Baseline, Logistic Regression, and XGBoost models.")

    df = data_loader.get_recent_risk_results(limit=100)

    if df.empty:
        st.info("No persisted M6 model predictions found in the database. Run model evaluations or make API /predict requests.")
        return

    # Visual gauge / metric overview of latest prediction
    latest = df.iloc[0]
    st.subheader("Latest Evaluated Transaction")
    col1, col2, col3, col4 = st.columns([2, 1, 1, 1])

    with col1:
        st.markdown(f"**Tx Hash**: `{_format_hex(latest['tx_hash'], 12, 10)}`")
        st.caption(f"Full: `{latest['tx_hash']}`")
    with col2:
        score = float(latest["risk_score"])
        st.metric("Risk Score (0–100)", f"{score:.2f}", delta=_get_risk_badge(score), delta_color="off")
        st.progress(min(max(score / 100.0, 0.0), 1.0))
    with col3:
        st.metric("Model", f"{latest['model_name']} (v{latest['model_version']})")
        st.write(f"Class: **{'Anomaly' if latest['predicted_class'] == 1 else 'Benign'}**")
    with col4:
        lat = float(latest["inference_latency_ms"]) if latest["inference_latency_ms"] else 0.0
        st.metric("Latency", f"{lat:.2f} ms")
        st.caption(f"Time: {latest['prediction_timestamp'][:19]}")

    st.markdown("---")

    # Table of all recent predictions
    st.subheader(f"Recent Risk Evaluations ({len(df)} records)")
    display_df = df.copy()
    display_df["display_hash"] = display_df["tx_hash"].apply(lambda h: _format_hex(h, 10, 8))
    display_df["risk_badge"] = display_df["risk_score"].apply(lambda s: _get_risk_badge(float(s)))
    display_df["latency_ms_fmt"] = display_df["inference_latency_ms"].apply(lambda l: f"{float(l):.2f} ms" if l else "-")
    display_df["class_label"] = display_df["predicted_class"].apply(lambda c: "Anomaly (1)" if c == 1 else "Benign (0)")

    st.dataframe(
        display_df[
            [
                "display_hash",
                "risk_badge",
                "class_label",
                "model_name",
                "model_version",
                "latency_ms_fmt",
                "reason_codes",
                "prediction_timestamp",
            ]
        ].rename(
            columns={
                "display_hash": "Tx Hash",
                "risk_badge": "Risk Level",
                "class_label": "Prediction",
                "model_name": "Model",
                "model_version": "Version",
                "latency_ms_fmt": "Latency",
                "reason_codes": "Reason Codes",
                "prediction_timestamp": "Timestamp",
            }
        ),
        use_container_width=True,
        hide_index=True,
    )
